import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compile } from "json-schema-to-typescript";

const schemaUrl = new URL(
  "../schema/realtime-protocol-v1.schema.json",
  import.meta.url,
);
const validatorOutputUrl = new URL(
  "../src/client/protocol/schema-validator.gen.ts",
  import.meta.url,
);
const typesOutputUrl = new URL(
  "../src/client/protocol/wire-types.gen.ts",
  import.meta.url,
);
const schemaSource = readFileSync(schemaUrl, "utf8");
const schema = JSON.parse(schemaSource);
const schemaHash = createHash("sha256").update(schemaSource).digest("hex");

// ajv compiles each `pattern` keyword to `<engine>(pattern, flags).test(value)`.
// The engine below only runs at generation time, where ajv keys its scope on the
// RegExp it returns. Standalone output calls `matchSchemaPattern` instead, which
// is emitted into the generated module (see matchSchemaPatternSource).
const schemaPatternEngine = Object.assign(
  (pattern, flags) => new RegExp(pattern, flags),
  { code: "matchSchemaPattern" },
);

const ajv = new Ajv2020({
  allErrors: false,
  code: {
    esm: true,
    lines: true,
    optimize: true,
    regExp: schemaPatternEngine,
    source: true,
  },
  discriminator: true,
  inlineRefs: false,
  messages: false,
  strict: true,
  validateFormats: false,
});
ajv.addSchema(schema);

const schemaId = schema.$id;
if (typeof schemaId !== "string") {
  throw new Error("Realtime protocol schema must define $id");
}

// Ajv delegates Unicode-aware string lengths to a CommonJS runtime helper.
// Inline that small counter so the generated ESM remains dependency-free.
const validatorSource = standaloneCode(ajv, {
  validateClientMessage: `${schemaId}#/$defs/clientMessage`,
  validateServerMessage: `${schemaId}#/$defs/serverMessage`,
}).replace(
  /const (func\d+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/g,
  (_, name) =>
    `const ${name} = (value) => { let length = 0; for (const _codePoint of value) length++; return length; };`,
);
if (validatorSource.includes("ajv/dist/runtime") || validatorSource.includes("require(")) {
  throw new Error("standalone validator unexpectedly depends on the Ajv runtime");
}

const schemaPatterns = {
  base64Cell: schema.$defs?.base64Cell?.properties?.base64?.pattern,
  heartbeatToken: schema.$defs?.heartbeatToken?.pattern,
  rowKey: schema.$defs?.rowKey?.pattern,
  u64: schema.$defs?.u64?.pattern,
};
if (Object.values(schemaPatterns).some((pattern) => typeof pattern !== "string")) {
  throw new Error("Realtime protocol schema is missing a generated error pattern");
}

// base64-cell.ts implements this pattern and no other. Refuse a schema that
// changes it, so the linear checker cannot silently stop matching the contract.
const IMPLEMENTED_BASE64_CELL_PATTERN =
  "^(?:[A-Za-z0-9+/]{4})*(?:[A-Za-z0-9+/][AQgw]==|[A-Za-z0-9+/]{2}[AEIMQUYcgkosw048]=)?$";
if (schemaPatterns.base64Cell !== IMPLEMENTED_BASE64_CELL_PATTERN) {
  throw new Error(
    "base64Cell pattern changed; update src/client/protocol/base64-cell.ts to match it before regenerating",
  );
}

// V8's RegExp overflows its stack on multi-megabyte base64 cells, so base64Cell
// is checked by isCanonicalBase64Cell instead. Every other pattern stays a RegExp.
const matchSchemaPatternSource = [
  "function matchSchemaPattern(pattern, flags) {",
  "  if (pattern === realtimeSchemaPatterns.base64Cell) return { test: isCanonicalBase64Cell };",
  "  return new RegExp(pattern, flags);",
  "}",
].join("\n");

const validatorGeneratedSource = [
  "// @ts-nocheck",
  "// Generated by packages/realtime/scripts/generate-protocol.mjs. Do not edit.",
  `// Source schema SHA-256: ${schemaHash}`,
  'import { isCanonicalBase64Cell } from "./base64-cell.js";',
  `export const realtimeSchemaPatterns = Object.freeze(${JSON.stringify(schemaPatterns, null, 2)});`,
  matchSchemaPatternSource,
  validatorSource.trimEnd(),
  "",
].join("\n");
// Keep the SDK type name independent of the schema's human-readable title.
const typeSchema = { ...schema, title: "RealtimeProtocolV1" };
const typesGeneratedSource = await compile(typeSchema, typeSchema.title, {
  bannerComment: [
    "// Generated by packages/realtime/scripts/generate-protocol.mjs. Do not edit.",
    `// Source schema SHA-256: ${schemaHash}`,
  ].join("\n"),
  style: {
    bracketSpacing: true,
    printWidth: 100,
    semi: true,
    singleQuote: false,
    tabWidth: 2,
    trailingComma: "all",
  },
});
const generatedOutputs = [
  { url: validatorOutputUrl, source: validatorGeneratedSource },
  { url: typesOutputUrl, source: typesGeneratedSource },
];

if (process.argv.includes("--check")) {
  for (const output of generatedOutputs) {
    let checkedInSource;
    try {
      checkedInSource = readFileSync(output.url, "utf8");
    } catch {
      checkedInSource = undefined;
    }
    if (checkedInSource !== output.source) {
      console.error(
        `${fileURLToPath(output.url)} is stale; run npm run generate:protocol --workspace @neon/realtime`,
      );
      process.exitCode = 1;
    }
  }
} else {
  for (const output of generatedOutputs) {
    writeFileSync(output.url, output.source);
  }
}
