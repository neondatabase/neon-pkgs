import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { compile } from "json-schema-to-typescript";

const schemaUrl = new URL(
  "../schema/neon-live-query-capability-v1.schema.json",
  import.meta.url,
);
const outputUrl = new URL(
  "../src/server/capability/schema/neon-live-query-capability-v1.gen.ts",
  import.meta.url,
);
const schemaSource = await readFile(schemaUrl, "utf8");
const schema = JSON.parse(schemaSource);
const schemaHash = createHash("sha256").update(schemaSource).digest("hex");
const generatedSource = await compile(schema, "NeonLiveQueryCapabilityV1", {
  bannerComment: [
    "// Generated by packages/live/scripts/generate-capability-types.mjs. Do not edit.",
    `// Source schema SHA-256: ${schemaHash}`,
  ].join("\n"),
  style: {
    bracketSpacing: true,
    printWidth: 100,
    semi: true,
    singleQuote: false,
    tabWidth: 2,
    trailingComma: "all",
  },
});

if (process.argv.includes("--check")) {
  let checkedInSource;
  try {
    checkedInSource = await readFile(outputUrl, "utf8");
  } catch {
    checkedInSource = undefined;
  }
  if (checkedInSource !== generatedSource) {
    console.error(
      `${fileURLToPath(outputUrl)} is stale; run npm run generate:capability --workspace @neon/live`,
    );
    process.exitCode = 1;
  }
} else {
  await writeFile(outputUrl, generatedSource);
}
